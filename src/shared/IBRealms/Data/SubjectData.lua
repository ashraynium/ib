function SubjectData.GetSubject(subjectId)
	for _, subject in ipairs(SubjectData.Subjects) do
		if subject.id == subjectId then
			return subject
		end
	end
	return nil
end

function SubjectData.GetSubjectsByCategory(categoryId)
	local results = {}
	for _, subject in ipairs(SubjectData.Subjects) do
		if subject.category == categoryId then
			table.insert(results, subject)
		end
	end
	return results
end

return SubjectData
